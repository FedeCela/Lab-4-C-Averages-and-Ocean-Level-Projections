#include <iostream>
using namespace std;

int main() {
    double NUMBER1 = 28;
    double NUMBER2 = 32;
    double NUMBER3 = 37;
    double NUMBER4 = 24;
    double NUMBER5 = 33;

    double SUM = NUMBER1 + NUMBER2 + NUMBER3 + NUMBER4 + NUMBER5;
    double AVERAGE = SUM / 5;
    cout << "The sum is: " << SUM << endl;
    cout << "The average is: " << AVERAGE << endl;

    return 0;
}
